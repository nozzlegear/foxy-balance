[<Collection("TransactionDatabase")>]
type ForecastServiceTests(fixture: DbContainerFixture) =
    let transactionDatabase: ITransactionDatabase = TransactionDatabase(TestDatabaseOptions fixture)
    let recurringTransactionDatabase: IRecurringTransactionDatabase = RecurringTransactionDatabase(TestDatabaseOptions fixture)
    let userDatabase: IUserDatabase = UserDatabase(TestDatabaseOptions fixture)
    let service = ForecastService(transactionDatabase, recurringTransactionDatabase)
    let bogus = Bogus.Faker()

    let createUser () =
        userDatabase.CreateAsync { EmailAddress = bogus.Internet.Email(); HashedPassword = bogus.Internet.Password() }

    let createTransaction (userId: UserId) (name: string) (amount: decimal) (date: DateTimeOffset) (txType: TransactionType) (status: TransactionStatus) =
        task {
            let partialTransaction: PartialTransaction =
                { Name = name
                  Amount = amount
                  DateCreated = date
                  Status = status
                  Type = txType
                  ImportId = Some (Guid.NewGuid().ToString())
                  RecurringTransactionId = None
                  AutoGenerated = false
                  MatchedTransactionId = None }
            return! transactionDatabase.CreateAsync(userId, partialTransaction)
        }

    let createCalendarDateBill (userId: UserId) (name: string) (amount: decimal) (dayOfMonth: int) =
        task {
            let partialBill: PartialRecurringTransaction =
                { Name = name
                  Amount = amount
                  Schedule = ScheduleType.ByCalendarDate { Date = dayOfMonth }
                  Type = RecurringTransactionType.Bill }
            return! recurringTransactionDatabase.CreateAsync(userId, partialBill)
        }

