    [<Fact>]
    member _.``BuildForecastAsync excludes toggled-off events from the calculation``() =
        task {
            let! user = createUser ()
            let now = DateTimeOffset(2026, 6, 15, 12, 0, 0, TimeSpan.Zero)
            let startDate = DateTimeOffset(2026, 6, 10, 0, 0, 0, TimeSpan.Zero)
            let endDate = DateTimeOffset(2026, 6, 30, 0, 0, 0, TimeSpan.Zero)

            let! _creditBefore =
                createTransaction user.Id "Salary" 100M (startDate.AddDays(-5.0)) Credit (Cleared (startDate.AddDays(-5.0)))
            let! _debitBefore =
                createTransaction user.Id "Groceries" 30M (startDate.AddDays(-3.0)) Debit (Cleared (startDate.AddDays(-3.0)))

            let expectedStartingBalance = 70M

            let! bonus =
                createTransaction user.Id "Bonus" 50M (startDate.AddDays(1.0)) Credit (Cleared (startDate.AddDays(1.0)))

            let! bill = createCalendarDateBill user.Id "Rent" 800M 20

            // First call: all events on (no includedEventIds → None).
            let! modelAll = service.BuildForecastAsync(user.Id, startDate, endDate, now)

            // Verify the Bonus row has the expected EventId.
            let bonusRowAll =
                modelAll.Rows |> List.find (fun r -> r.Description = "Bonus")
            %bonusRowAll.EventId.Should().Be(Some (sprintf "t%i" bonus.Id))

            // Second call: only the Rent occurrence is toggled on (Bonus toggled off).
            let rentEventId = sprintf "r%i-2026-06-20" bill.Id
            let includedIds = Set [ rentEventId ]
            let! model = service.BuildForecastAsync(user.Id, startDate, endDate, now, includedEventIds = includedIds)

            // Bonus row should be toggled off with carried balance (= starting balance, not +50).
            let bonusRow =
                model.Rows |> List.find (fun r -> r.Description = "Bonus")
            %bonusRow.IsToggledOff.Should().Be(true)
            %bonusRow.RunningBalance.Should().Be(expectedStartingBalance)

            // Rent row should be on, balance = 70 - 800 = -730.
            let rentRow =
                model.Rows |> List.find (fun r -> r.Description = "Rent")
            %rentRow.IsToggledOff.Should().Be(false)
            %rentRow.RunningBalance.Should().Be(expectedStartingBalance - 800M)

            // Projected balance should be -730 (Bonus excluded).
            let lastRow = model.Rows |> List.last
            %lastRow.RunningBalance.Should().Be(expectedStartingBalance - 800M)

            // Chart should have no entry for the Bonus date.
            let bonusDateStr = "2026-06-11"
            let chartHasBonusDate = model.ChartDates |> List.contains bonusDateStr
            %chartHasBonusDate.Should().Be(false)
        }

