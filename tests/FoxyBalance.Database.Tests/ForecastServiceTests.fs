    // ── BuildForecastAsync tests (DB) ──

    [<Fact>]
    member _.``BuildForecastAsync backfills starting balance and real transactions and projects recurring bills``() =
        task {
            // Setup
            let! user = createUser ()

            // Anchor "today" at a fixed date so the test is deterministic.
            let now = DateTimeOffset(2026, 6, 15, 12, 0, 0, TimeSpan.Zero)

            // startDate is 5 days before today, endDate is 15 days after today.
            let startDate = DateTimeOffset(2026, 6, 10, 0, 0, 0, TimeSpan.Zero)
            let endDate = DateTimeOffset(2026, 6, 30, 0, 0, 0, TimeSpan.Zero)

            // Seed a cleared credit before startDate → contributes +100 to starting balance.
            let! _creditBefore =
                createTransaction user.Id "Salary" 100M (startDate.AddDays(-5.0)) Credit (Cleared (startDate.AddDays(-5.0)))

            // Seed a cleared debit before startDate → contributes -30 to starting balance.
            let! _debitBefore =
                createTransaction user.Id "Groceries" 30M (startDate.AddDays(-3.0)) Debit (Cleared (startDate.AddDays(-3.0)))

            // Expected starting balance = 100 - 30 = 70.
            let expectedStartingBalance = 70M

            // Seed a real credit inside [startDate, today] → should appear as an event.
            let! _realCredit =
                createTransaction user.Id "Bonus" 50M (startDate.AddDays(1.0)) Credit (Cleared (startDate.AddDays(1.0)))

            // Create an active recurring ByCalendarDate bill on the 20th (which is > today=15, inside window).
            let! _bill = createCalendarDateBill user.Id "Rent" 800M 20

            // Act
            let! model = service.BuildForecastAsync(user.Id, startDate, endDate, now)

            // Assert: starting balance
            %model.StartingBalance.Should().Be(expectedStartingBalance)
            %model.StartDateStr.Should().Be("2026-06-10")
            %model.EndDateStr.Should().Be("2026-06-30")

            // Assert: leading "Starting balance" row
            let firstRow = model.Rows |> List.head
            %firstRow.Label.Should().Be("Starting balance")
            %firstRow.Amount.Should().Be(None)
            %firstRow.RunningBalance.Should().Be(expectedStartingBalance)

            // Assert: trailing "Projected end-date balance" row
            let lastRow = model.Rows |> List.last
            %lastRow.Label.Should().Be("Projected end-date balance")
            %lastRow.Amount.Should().Be(None)

            // Assert: real credit event appears and shifts running balance.
            let realCreditRow =
                model.Rows
                |> List.find (fun r -> r.Description = "Bonus")
            %realCreditRow.Label.Should().Be("Income")
            %realCreditRow.Amount.Should().Be(Some 50M)
            %realCreditRow.RunningBalance.Should().Be(expectedStartingBalance + 50M)

            // Assert: predicted bill appears at the 20th with negative amount.
            let billRow =
                model.Rows
                |> List.find (fun r -> r.Description = "Rent")
            %billRow.Label.Should().Be("Bill")
            %billRow.Date.Date.Should().Be(DateTimeOffset(2026, 6, 20, 0, 0, 0, TimeSpan.Zero).Date)
            %billRow.Amount.Should().Be(Some -800M)
            %billRow.RunningBalance.Should().Be(expectedStartingBalance + 50M - 800M)

            // Assert: event rows are chronological.
            let eventRows =
                model.Rows
                |> List.filter (fun r -> r.Amount.IsSome)
            let dates = eventRows |> List.map (fun r -> r.Date.Date)
            let sortedDates = List.sort dates
            %dates.Should().Be(sortedDates)

            // Assert: chart arrays are aligned and start with starting balance.
            %model.ChartDates.Head.Should().Be("2026-06-10")
            %model.ChartBalances.Head.Should().Be(expectedStartingBalance)
            %model.ChartDates.Length.Should().BeGreaterThan(1)
            %model.ChartBalances.Length.Should().Be(model.ChartDates.Length)
        }

