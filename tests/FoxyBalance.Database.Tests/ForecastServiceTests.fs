    [<Fact>]
    member _.``BuildForecastAsync includes temporary recurring transactions without persisting``() =
        task {
            let! user = createUser ()
            let now = DateTimeOffset(2026, 6, 15, 12, 0, 0, TimeSpan.Zero)
            let startDate = DateTimeOffset(2026, 6, 10, 0, 0, 0, TimeSpan.Zero)
            let endDate = DateTimeOffset(2026, 6, 30, 0, 0, 0, TimeSpan.Zero)

            let! _creditBefore =
                createTransaction user.Id "Salary" 100M (startDate.AddDays(-5.0)) Credit (Cleared (startDate.AddDays(-5.0)))

            let startingBalance = 100M

            // Temp item: bill on the 25th.
            let tempItems : TempRecurringTransaction list =
                [ { Name = "New bill"; Amount = 100M; Schedule = ScheduleType.ByCalendarDate { Date = 25 }; Type = RecurringTransactionType.Bill } ]

            let! model =
                service.BuildForecastAsync(user.Id, startDate, endDate, now,
                                           temporaryRecurringTransactions = tempItems)

            // The temp row should appear with negative amount and IsTemporary = true.
            let tempRow =
                model.Rows |> List.find (fun r -> r.Description = "New bill")
            %tempRow.Amount.Should().Be(Some -100M)
            %tempRow.IsTemporary.Should().Be(true)
            %tempRow.EventId.Value.StartsWith("x0-").Should().Be(true)
            %tempRow.RunningBalance.Should().Be(startingBalance - 100M)
            %tempRow.IsToggledOff.Should().Be(false)

            // Nothing was persisted to the recurring transaction DB.
            let! recs = recurringTransactionDatabase.ListAsync(user.Id, true)
            %(Seq.length recs).Should().Be(0)

            // Temp occurrence on/before today is filtered: temp on the 15th with now = June 15 should NOT appear.
            let tempToday : TempRecurringTransaction list =
                [ { Name = "Today bill"; Amount = 50M; Schedule = ScheduleType.ByCalendarDate { Date = 15 }; Type = RecurringTransactionType.Bill } ]
            let! model2 =
                service.BuildForecastAsync(user.Id, startDate, endDate, now,
                                           temporaryRecurringTransactions = tempToday)
            let todayBillRows =
                model2.Rows |> List.filter (fun r -> r.Description = "Today bill")
            %todayBillRows.Length.Should().Be(0)
        }

